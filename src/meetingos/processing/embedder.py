"""Embedding generation with long-turn splitting and versioning.

Guarantees that conversation turns or chunks exceeding the model's max_seq_length
are not silently truncated. Oversized texts are partitioned into overlapping
segments, each embedded and mapped back to the parent chunk_id.
"""
from __future__ import annotations

import hashlib
import sqlite3
from dataclasses import dataclass
from datetime import datetime, timezone
from typing import Optional, Sequence

import numpy as np

from meetingos.config import (
    DEFAULT_CHUNK_WINDOW,
    EMBEDDING_DIM,
    EMBEDDING_MAX_SEQ_LENGTH,
    EMBEDDING_MODEL,
    EMBEDDING_NORMALIZATION,
    LONG_TURN_STRIDE_TOKENS,
)
from meetingos.models import Chunk, EmbeddingConfig


@dataclass
class EmbeddingSegment:
    """An embedding representation unit."""
    chunk_id:        str
    segment_index:   int
    text:            str
    token_count:     int
    is_subsegment:   bool  # True if generated by long-turn splitting


class TextEmbedder:
    """Manages sentence embedding generation with long-turn splitting."""

    def __init__(
        self,
        model_name: str = EMBEDDING_MODEL,
        max_seq_length: int = EMBEDDING_MAX_SEQ_LENGTH,
        dim: int = EMBEDDING_DIM,
        stride_tokens: int = LONG_TURN_STRIDE_TOKENS,
        lazy_load: bool = True,
        use_mock: bool = False,
    ):
        self.model_name = model_name
        self.max_seq_length = max_seq_length
        self.dim = dim
        self.stride_tokens = stride_tokens
        self.use_mock = use_mock
        self._model = None
        if not lazy_load and not use_mock:
            self._load_model()

    def _load_model(self):
        if self._model is None:
            import os
            os.environ["HF_HUB_DISABLE_XET"] = "1"
            from sentence_transformers import SentenceTransformer
            try:
                self._model = SentenceTransformer(self.model_name, local_files_only=True)
            except Exception:
                self._model = SentenceTransformer(self.model_name)
            # Verify actual model max_seq_length at runtime
            actual_max = getattr(self._model, "max_seq_length", self.max_seq_length)
            self.max_seq_length = min(self.max_seq_length, actual_max)

    def create_config_record(
        self,
        chunking_version: str = f"w{DEFAULT_CHUNK_WINDOW}_v1",
        model_revision: str = "main",
    ) -> EmbeddingConfig:
        """Create a deterministic versioned EmbeddingConfig."""
        config_payload = f"{self.model_name}:{model_revision}:{self.dim}:{self.max_seq_length}:{EMBEDDING_NORMALIZATION}:{chunking_version}"
        config_id = hashlib.sha256(config_payload.encode("utf-8")).hexdigest()[:16]

        return EmbeddingConfig(
            config_id=config_id,
            embedding_model=self.model_name,
            model_revision=model_revision,
            embedding_dim=self.dim,
            max_seq_length=self.max_seq_length,
            normalization=EMBEDDING_NORMALIZATION,
            chunking_version=chunking_version,
            created_at=datetime.now(timezone.utc).isoformat(),
        )

    def segment_chunk(self, chunk: Chunk) -> list[EmbeddingSegment]:
        """
        Partition a chunk into one or more embedding segments.

        If chunk token count fits in max_seq_length: returns single segment.
        If chunk token count exceeds max_seq_length: splits by words with overlap,
        ensuring content at the tail of long turns is never truncated.
        """
        words = chunk.text.split()
        # Approximate tokens as ~1.3 tokens per word -> max words ~ max_seq_length / 1.3
        max_words = int(self.max_seq_length / 1.3)
        stride_words = int(self.stride_tokens / 1.3)

        if len(words) <= max_words:
            return [EmbeddingSegment(
                chunk_id=chunk.chunk_id,
                segment_index=0,
                text=chunk.text,
                token_count=chunk.token_count,
                is_subsegment=False,
            )]

        # Split into overlapping word windows
        segments: list[EmbeddingSegment] = []
        seg_idx = 0
        start = 0

        while start < len(words):
            end = min(start + max_words, len(words))
            sub_words = words[start:end]
            sub_text = " ".join(sub_words)
            segments.append(EmbeddingSegment(
                chunk_id=chunk.chunk_id,
                segment_index=seg_idx,
                text=sub_text,
                token_count=int(len(sub_words) * 1.3),
                is_subsegment=True,
            ))
            seg_idx += 1
            if end >= len(words):
                break
            start += stride_words

        return segments

    def embed_texts(self, texts: list[str]) -> np.ndarray:
        """
        Generate L2-normalized embeddings for a list of texts.
        Returns float32 ndarray of shape (len(texts), dim).
        """
        if not texts:
            return np.empty((0, self.dim), dtype=np.float32)

        if self.use_mock:
            # Deterministic L2-normalized pseudo-vectors for fast offline tests
            arr = np.zeros((len(texts), self.dim), dtype=np.float32)
            for i, text in enumerate(texts):
                h = hashlib.sha256(text.encode("utf-8")).digest()
                raw_ints = np.frombuffer(h * (self.dim // 32 + 1), dtype=np.int8)[:self.dim]
                vec = raw_ints.astype(np.float32)
                norm = np.linalg.norm(vec)
                arr[i] = vec / (norm if norm > 0 else 1.0)
            return arr

        self._load_model()
        embeddings = self._model.encode(
            texts,
            batch_size=32,
            show_progress_bar=False,
            normalize_embeddings=True,  # L2 normalization for Inner Product cosine sim
            convert_to_numpy=True,
        )
        return embeddings.astype(np.float32)

    def embed_query(self, query: str) -> np.ndarray:
        """Embed a single query into a 2D float32 array (1, dim)."""
        return self.embed_texts([query])


def save_embedding_config(config: EmbeddingConfig, conn: sqlite3.Connection) -> None:
    """Store or replace an embedding configuration in SQLite."""
    with conn:
        conn.execute(
            """
            INSERT OR REPLACE INTO embedding_configs (
                config_id, embedding_model, model_revision, embedding_dim,
                max_seq_length, normalization, chunking_version, created_at
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                config.config_id,
                config.embedding_model,
                config.model_revision,
                config.embedding_dim,
                config.max_seq_length,
                config.normalization,
                config.chunking_version,
                config.created_at,
            ),
        )


def get_embedding_config(config_id: str, conn: sqlite3.Connection) -> Optional[EmbeddingConfig]:
    """Retrieve an embedding configuration by ID."""
    row = conn.execute(
        "SELECT * FROM embedding_configs WHERE config_id = ?",
        (config_id,),
    ).fetchone()
    if not row:
        return None
    return EmbeddingConfig(
        config_id=row["config_id"],
        embedding_model=row["embedding_model"],
        model_revision=row["model_revision"],
        embedding_dim=row["embedding_dim"],
        max_seq_length=row["max_seq_length"],
        normalization=row["normalization"],
        chunking_version=row["chunking_version"],
        created_at=row["created_at"],
    )
